#!/usr/bin/env node
/*
  Generates src/components/sketchPaths.ts — the one-line section motifs that
  ScrollPath weaves into its single drawn line (About face, Skills gears,
  Experience growth graph, Projects rocket, Achievements trophy,
  Certifications certificate, plus the Contact hands+book terminal).

  Each motif's `d` is a SINGLE continuous stroke that enters at `entry` and
  leaves at `exit`, so the page line can flow in, draw the object, and flow
  on to the next one.

  Sources (2026-07-05): svg/<name>.png — the user's one-line artworks. The
  .svg files beside them embed the same art as base64 rasters, so the PNG is
  the ink source: decode → threshold → thin → graph → route → fit
  (scripts/centerline/), one full-coverage centerline trace per artwork.

      node scripts/generate-sketch-paths.mjs            # writes sketchPaths.ts
      node scripts/generate-sketch-paths.mjs --gallery  # + sketch-gallery.html
*/

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { traceArtwork } from './centerline/index.mjs';
import { decodePng, inkBitmap } from './centerline/png.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const fmt = v => {
  const s = (Math.round(v * 10) / 10).toFixed(1);
  return s.endsWith('.0') ? s.slice(0, -2) : s;
};

/* section id → artwork file (svg/<file>.png) and the trace's entry/exit
   hints in PNG PIXEL coords — each aimed at the drawing's own line tails
   (the router snaps them to the nearest skeleton endpoint). fx/fy are
   fractions of the image box. */
/* Entry/exit fractions aimed at each drawing's REAL stroke tips (the
   degree-1 skeleton endpoints, measured 2026-07-05) so the pen starts and
   ends exactly where the artist's single line does — following the stroke
   from its true start means (near-)zero retracing. */
const SPEC = {
  about:          { file: 'face',        entry: [0.383, 0.213], exit: [0.43, 0.985] }, // eye tip (153,174) in, bottom swoosh (172,804) out
  skills:         { file: 'gears',       entry: [0.454, 0.019], exit: [0.795, 0.998] },// top tail (475,26) in, bottom tail (833,1372) out
  experience:     { file: 'graph',       entry: [0.95, 0.2],    exit: [0.005, 0.783] },// arrow tip in, left-edge tick (2,372) out
  projects:       { file: 'rocket',      entry: [0.595, 0.54],  exit: [0.619, 0.921] },// stroke tip by the right fin (231,240) in (user-marked), flame's curved tail (240,409) out
  achievements:   { file: 'trophy',      entry: [0.5, 0],       exit: [0.5, 1] },      // rim in, ground-line tip out
  certifications: { file: 'certificate', entry: [0.208, 0.59],  exit: [0.697, 0.584] },// left tick (216,614) in, right tick (725,608) out
  hands:          { file: 'hands',       entry: [0.608, 0.105], exit: [0.46, 0.846] }, // sleeve tick (841,167) in, lower cuff (637,1343) out — THE LINE ENDS HERE
};

const VB_H = 300; // every motif normalized to a 300-unit-tall local box
// Normalize the WORKING resolution: small sources supersample up to 2x (so
// close parallel strokes thin cleanly); oversized sources (the 2026-07-06
// face is 1250x2550 with ~10px-thick strokes) scale DOWN toward ~1700 on the
// long side — a uniform ~2-4px ink width is what the pipeline's junction
// thresholds and direction windows are tuned for.
const TARGET_DIM = 1700;

const traced = {};
const vbs = {};
const pngB64 = {};
for (const [id, spec] of Object.entries(SPEC)) {
  const buf = readFileSync(join(ROOT, `svg/${spec.file}.png`));
  const img = decodePng(buf);
  const bmp = inkBitmap(img, { scale: Math.min(2, TARGET_DIM / Math.max(img.w, img.h)) });
  const ls = VB_H / bmp.h;
  vbs[id] = [Math.round(bmp.w * ls), VB_H];
  pngB64[id] = buf.toString('base64');
  traced[id] = traceArtwork({
    name: id,
    bmp,
    entryHint: [spec.entry[0] * bmp.w, spec.entry[1] * bmp.h],
    exitHint: [spec.exit[0] * bmp.w, spec.exit[1] * bmp.h],
    toLocal: ([x, y]) => [x * ls, y * ls],
    localScale: ls,
  });
  const s = traced[id].stats;
  console.log(
    `${id.padEnd(14)} ${String(img.w).padStart(4)}x${String(img.h).padEnd(4)}` +
    ` comps=${s.components} connectors=${s.connectors}` +
    ` connLen=${s.connectorLen.toFixed(0)} retrace=${s.retraceLen.toFixed(0)}` +
    ` ink=${s.edgeLen.toFixed(0)} route=${s.routeLen.toFixed(0)} beziers=${s.beziers}`,
  );
}

/* ── emit the TypeScript module ── */
const ids = Object.keys(SPEC);
const ts = `/*
  GENERATED by scripts/generate-sketch-paths.mjs — do not edit by hand.
  Seven one-line motifs (traced from svg/*.png), woven into ScrollPath's
  single line: each \`d\` is a SINGLE continuous stroke tracing every stroke
  of the artwork — it enters at \`entry\` and leaves at \`exit\`, so the page
  line flows through it. 'hands' is the Contact terminal: the line ENDS on
  its trailing stroke.
*/

export type SketchId =
${ids.map(id => `  | '${id}'`).join('\n')};

export interface SketchDef {
  /** viewBox width/height — the motif's local coordinate box */
  vb: readonly [number, number];
  d: string;
  /** where the page line flows in / out, in vb coords */
  entry: readonly [number, number];
  exit: readonly [number, number];
  /** mask-stroke width (local units) that covers the ink's widest stroke */
  maskW: number;
}

export const SKETCHES: Record<SketchId, SketchDef> = {
${ids
  .map(id => {
    const t = traced[id];
    return `  ${id}: {\n    vb: [${vbs[id][0]}, ${vbs[id][1]}],\n    d: '${t.d}',\n    entry: [${t.entry.map(fmt).join(', ')}],\n    exit: [${t.exit.map(fmt).join(', ')}],\n    maskW: ${fmt(t.maskW)},\n  },`;
  })
  .join('\n')}
};
`;
writeFileSync(join(ROOT, 'src/components/sketchPaths.ts'), ts);
console.log('wrote src/components/sketchPaths.ts');

/* ── optional visual gallery for iterating on the shapes ── */
if (process.argv.includes('--gallery')) {
  const cards = ids
    .map(id => {
      const t = traced[id];
      const [vw, vh] = vbs[id];
      return `
    <figure>
      <svg viewBox="0 0 ${vw} ${vh}" style="width:${vw * 1.1}px">
        <image href="data:image/png;base64,${pngB64[id]}" x="0" y="0" width="${vw}" height="${vh}" opacity="0.22"/>
        <path class="track" d="${t.d}" />
        <path class="ink" pathLength="100" d="${t.d}" />
        <circle cx="${t.entry[0]}" cy="${t.entry[1]}" r="4" fill="#16a34a" stroke="none"/>
        <circle cx="${t.exit[0]}" cy="${t.exit[1]}" r="4" fill="#dc2626" stroke="none"/>
      </svg>
      <figcaption>${id}</figcaption>
    </figure>`;
    })
    .join('\n');
  const html = `<!doctype html>
<meta charset="utf-8">
<title>sketch gallery</title>
<style>
  body { font: 14px system-ui; background: #fff; margin: 24px; }
  .grid { display: flex; flex-wrap: wrap; gap: 28px; align-items: flex-end; }
  figure { margin: 0; padding: 14px; border: 1px solid #e5e7eb; border-radius: 12px; }
  figcaption { text-align: center; color: #6b7280; margin-top: 8px; }
  svg { overflow: visible; display: block; }
  path { fill: none; stroke-linecap: round; stroke-linejoin: round; }
  .track { stroke: rgba(79,70,229,0.16); stroke-width: 1.6; }
  .ink { stroke: #4f46e5; stroke-width: 1.6; stroke-dasharray: 100;
         stroke-dashoffset: calc(100 - var(--p)); }
  header { display: flex; gap: 16px; align-items: center; margin-bottom: 20px; }
  input { width: 340px; }
</style>
<header>
  <input id="p" type="range" min="0" max="100" value="100">
  <span id="v">100%</span> drawn
</header>
<div class="grid">${cards}</div>
<script>
  const set = v => { document.body.style.setProperty('--p', v);
    document.getElementById('v').textContent = v + '%'; };
  document.getElementById('p').oninput = e => set(e.target.value);
  set(100);
</script>`;
  writeFileSync(join(ROOT, 'sketch-gallery.html'), html);
  console.log('wrote sketch-gallery.html');
}
